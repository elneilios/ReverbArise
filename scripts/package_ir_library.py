"""Package the listening-approved revision-1 library; never silently revise content."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
APPROVED={
    "monumental":("Monumental","0799b724acba5b66f3e933109a79454673da944d022f2ac13a8d6cb2a0532148","Long, intense cinematic build with broad stereo diffusion; deliberately stronger level."),
    "intimate-plate":("IntimatePlate","fad9e920013101794af9050fbf88d784f65ccb7fd65523e963998a2853b10c1c","Compact bright plate lift with a narrow image."),
    "vintage-dark-hall":("VintageDarkHall","1f86a72cbf8fcdae256ea8a8765705fd227ae1adaf94594908c80fd2f370d65c","Warm low resonances and strongly damped highs."),
    "shimmer-cloud":("ShimmerCloud","16d1ea58c5db5ae1bf110ceea30da6a88276092a40bb34f25745f72f7d9eee7f","Broad static resonant coloration; no dynamic pitch shifting."),
    "whisper":("Whisper","59f013118f8daccb87b93c9b125c385d620f50e72e710bede6eedcd93d5387c7","Short, narrow, airy transient anticipation.")}


def package(source,check):
    manifest=json.loads((source/'manifest.json').read_text(encoding='utf-8'))
    assert manifest['generator']=='ir-library-prototype-v4'
    files={};entries=[];inc=['// Generated by scripts/package_ir_library.py from approved immutable audio.']
    for entry in manifest['entries']:
        ident=entry['parameters']['id'];stem,expected,description=APPROVED[ident]
        data=(source/entry['file']).read_bytes()
        assert hashlib.sha256(data).hexdigest()==expected==entry['wav_sha256'],ident
        files[ROOT/'resources/irs'/f'{stem}.wav']=data
        entry=dict(entry,prototype=False,file=f'{stem}.wav',description=description)
        entries.append(entry)
        inc.extend([f',{{"{ident}",1,"{entry["parameters"]["name"]}","{description}","CC0-1.0","{manifest["generator"]}",',
                    f' 48000,2,24,{entry["frames"]},PreverbResources::{stem}_wav,static_cast<size_t>(PreverbResources::{stem}_wavSize),',
                    f' "{expected}","{entry["canonical_sample_sha256"]}"}}'])
    assert {e['parameters']['id'] for e in entries}==set(APPROVED)
    manifest=dict(manifest,entries=entries,prototypes_pending_listening=False,listening_approved='2026-11-02',release_revision=1)
    files[ROOT/'resources/irs/manifest.json']=(json.dumps(manifest,indent=2)+'\n').encode()
    files[ROOT/'resources/irs/LICENSE.md']=(ROOT/'scripts/IR_AUDIO_LICENSE.md').read_bytes()
    files[ROOT/'Source/DSP/BundledImpulseEntries.inc']=('\n'.join(inc)+'\n').encode()
    for path,content in files.items():
        if path.exists():
            assert path.read_bytes()==content,f'{path}: immutable release differs; new revision needed'
        elif check:
            raise AssertionError(f'Missing released file: {path}')
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(content)
    assert hashlib.sha256((ROOT/'resources/PreverbHall.wav').read_bytes()).hexdigest()=='b7275a27fc7629a9a1a7191abda4fbb3c8a46372dc9071e36dc1112e4839b458'
    print(('Verified' if check else 'Packaged')+' five approved revision-1 IRs; original Hall unchanged')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,default=Path('out/ir-library-prototypes-v4'));p.add_argument('--check',action='store_true')
    args=p.parse_args();package(args.source,args.check)
